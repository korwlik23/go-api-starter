// Package storage defines the private object-storage boundary used by media
// modules. Implementations may be local filesystem providers or remote object
// stores, but callers only receive opaque keys and metadata.
package storage

import (
	"context"
	"errors"
	"io"
	"strings"
	"time"
)

var (
	ErrInvalidProvider = errors.New("invalid storage provider")
	ErrInvalidContext  = errors.New("invalid storage context")
	ErrInvalidRequest  = errors.New("invalid storage request")
	ErrInvalidKey      = errors.New("invalid storage object key")
	ErrInvalidObject   = errors.New("invalid storage object")
	ErrObjectNotFound  = errors.New("storage object not found")
	ErrObjectExists    = errors.New("storage object already exists")
	ErrSizeMismatch    = errors.New("storage object size mismatch")
)

// PutRequest contains an object body. Size is optional; use -1 when the size
// is not known in advance. Providers must not treat a caller-provided key as a
// filesystem path; the returned key is generated by the provider.
type PutRequest struct {
	Body io.Reader
	Size int64
}

// ObjectInfo is safe metadata for an object stored by an ObjectStore. It does
// not contain a public URL or a caller-controlled path.
type ObjectInfo struct {
	Key     string
	Size    int64
	ModTime time.Time
}

// ObjectStore is the storage boundary shared by media application services.
// Delete is idempotent so a failed finalize can compensate safely.
type ObjectStore interface {
	Put(context.Context, PutRequest) (ObjectInfo, error)
	Stat(context.Context, string) (ObjectInfo, error)
	Delete(context.Context, string) error
	Open(context.Context, string) (io.ReadCloser, ObjectInfo, error)
}

func ValidateContext(ctx context.Context) error {
	if ctx == nil {
		return ErrInvalidContext
	}
	return nil
}

func ValidatePutRequest(request PutRequest) error {
	if request.Body == nil || request.Size < -1 {
		return ErrInvalidRequest
	}
	return nil
}

func NormalizeKey(key string) string {
	return strings.TrimSpace(key)
}
